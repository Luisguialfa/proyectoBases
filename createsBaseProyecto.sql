CREATE DATABASE tiendaDeportiva
USE tiendaDeportiva

-- Tabla clientes
CREATE TABLE CLIENTE (
	idCliente INT NOT NULL,
	nombreCliente NVARCHAR(50),
	apellidoCliente NVARCHAR(50),
	correoCliente NVARCHAR(100),
	telefonoCliente NVARCHAR(20)
)
ALTER TABLE CLIENTE
	ADD CONSTRAINT PK_CLIENTE PRIMARY KEY (iDCliente)

-- Tabla de roles
CREATE TABLE ROL (
    idRol INT NOT NULL,
    nombreRol NVARCHAR(50) NOT NULL,
    descripcionRol NVARCHAR(150)
)
ALTER TABLE ROL ADD CONSTRAINT PK_ROL PRIMARY KEY (idRol)

-- Tabla Usuarios
CREATE TABLE USUARIO (
    idUsuario INT NOT NULL,
    idCliente INT,
    idRol INT NOT NULL,
    nombreUsuario NVARCHAR(50),
    passwordHash NVARCHAR(255),
    fechaCreacion DATETIME,
    activo BIT
)
ALTER TABLE USUARIO ADD CONSTRAINT PK_USUARIO PRIMARY KEY (idUsuario)
ALTER TABLE USUARIO ADD CONSTRAINT FK_USUARIO_CLIENTE FOREIGN KEY (idCliente) REFERENCES CLIENTE(idCliente)
ALTER TABLE USUARIO ADD CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (idRol) REFERENCES ROL(idRol)

-- Tabla Pais
CREATE TABLE PAIS (
    idPais INT NOT NULL,
    nombrePais NVARCHAR(100)
)
ALTER TABLE PAIS ADD CONSTRAINT PK_PAIS PRIMARY KEY (idPais)

-- Tabla Provincia
CREATE TABLE PROVINCIA (
    idProvincia INT NOT NULL,
    idPais INT NOT NULL,
    nombreProvincia NVARCHAR(100)
)
ALTER TABLE PROVINCIA ADD CONSTRAINT PK_PROVINCIA PRIMARY KEY (idProvincia)
ALTER TABLE PROVINCIA ADD CONSTRAINT FK_PROVINCIA_PAIS FOREIGN KEY (idPais) REFERENCES PAIS(idPais)

-- Tabla Canton
CREATE TABLE CANTON (
    idCanton INT NOT NULL,
    idProvincia INT NOT NULL,
    nombreCanton NVARCHAR(100)
)
ALTER TABLE CANTON ADD CONSTRAINT PK_CANTON PRIMARY KEY (idCanton)
ALTER TABLE CANTON ADD CONSTRAINT FK_CANTON_PROVINCIA FOREIGN KEY (idProvincia) REFERENCES PROVINCIA(idProvincia)

-- Tabla Distrito
CREATE TABLE DISTRITO (
    idDistrito INT NOT NULL,
    idCanton INT NOT NULL,
    nombreDistrito NVARCHAR(100)
)
ALTER TABLE DISTRITO ADD CONSTRAINT PK_DISTRITO PRIMARY KEY (idDistrito)
ALTER TABLE DISTRITO ADD CONSTRAINT FK_DISTRITO_CANTON FOREIGN KEY (idCanton) REFERENCES CANTON(idCanton)

-- Tabla direcciones
CREATE TABLE DIRECCION (
    idDireccion INT NOT NULL,
    idCliente INT NOT NULL,
    idPais INT NOT NULL,
    idProvincia INT NOT NULL,
    idCanton INT NOT NULL,
    idDistrito INT NOT NULL,
    otrasReferencia NVARCHAR(255)
)
ALTER TABLE DIRECCION ADD CONSTRAINT PK_DIRECCION PRIMARY KEY (idDireccion)
ALTER TABLE DIRECCION ADD CONSTRAINT FK_DIRECCION_CLIENTE FOREIGN KEY (idCliente) REFERENCES CLIENTE(idCliente)
ALTER TABLE DIRECCION ADD CONSTRAINT FK_DIRECCION_PAIS FOREIGN KEY (idPais) REFERENCES PAIS(idPais)
ALTER TABLE DIRECCION ADD CONSTRAINT FK_DIRECCION_PROVINCIA FOREIGN KEY (idProvincia) REFERENCES PROVINCIA(idProvincia)
ALTER TABLE DIRECCION ADD CONSTRAINT FK_DIRECCION_CANTON FOREIGN KEY (idCanton) REFERENCES CANTON(idCanton)
ALTER TABLE DIRECCION ADD CONSTRAINT FK_DIRECCION_DISTRITO FOREIGN KEY (idDistrito) REFERENCES DISTRITO(idDistrito)

-- Tabla Marca
CREATE TABLE MARCA (
    idMarca INT NOT NULL,
    nombreMarca NVARCHAR(100),
    descripcionMarca NVARCHAR(255)
)
ALTER TABLE MARCA ADD CONSTRAINT PK_MARCA PRIMARY KEY (idMarca)

-- Tabla Producto
CREATE TABLE PRODUCTO (
    idProducto INT NOT NULL,
    idMarca INT NOT NULL,
    nombreProducto NVARCHAR(150),
    descripcionProducto NVARCHAR(300),
    precioProducto DECIMAL(12,2),
    activo BIT
)
ALTER TABLE PRODUCTO ADD CONSTRAINT PK_PRODUCTO PRIMARY KEY (idProducto)
ALTER TABLE PRODUCTO ADD CONSTRAINT FK_PRODUCTO_MARCA FOREIGN KEY (idMarca) REFERENCES MARCA(idMarca)

-- Tabla Catoria
CREATE TABLE CATEGORIA (
    idCategoria INT NOT NULL,
    nombreCategoria NVARCHAR(100),
    descripcionCategoria NVARCHAR(255)
)
ALTER TABLE CATEGORIA ADD CONSTRAINT PK_CATEGORIA PRIMARY KEY (idCategoria)

-- Tabla de la asociasion de los productos
CREATE TABLE PRODUCTO_CATEGORIA (
    idProducto INT NOT NULL,
    idCategoria INT NOT NULL
)
ALTER TABLE PRODUCTO_CATEGORIA ADD CONSTRAINT PK_PRODUCTO_CATEGORIA PRIMARY KEY (idProducto, idCategoria)
ALTER TABLE PRODUCTO_CATEGORIA ADD CONSTRAINT FK_PRODUCTO_CATEGORIA_PRODUCTO FOREIGN KEY (idProducto) REFERENCES PRODUCTO(idProducto)
ALTER TABLE PRODUCTO_CATEGORIA ADD CONSTRAINT FK_PRODUCTO_CATEGORIA_CATEGORIA FOREIGN KEY (idCategoria) REFERENCES CATEGORIA(idCategoria)

-- Tabla Imagenes de productos
CREATE TABLE IMAGEN_PRODUCTO (
    idImagen INT NOT NULL,
    idProducto INT NOT NULL,
    urlImagen NVARCHAR(500),
    esPrincipal BIT
)
ALTER TABLE IMAGEN_PRODUCTO ADD CONSTRAINT PK_IMAGEN_PRODUCTO PRIMARY KEY (idImagen)
ALTER TABLE IMAGEN_PRODUCTO ADD CONSTRAINT FK_IMAGEN_PRODUCTO_PRODUCTO FOREIGN KEY (idProducto) REFERENCES PRODUCTO(idProducto)

--Tabla inventario
CREATE TABLE INVENTARIO (
    idInventario INT NOT NULL,
    idProducto INT NOT NULL,
    cantidadDisponible INT,
    cantidadReservada INT,
    ultimaActualizacion DATETIME
)
ALTER TABLE INVENTARIO ADD CONSTRAINT PK_INVENTARIO PRIMARY KEY (idInventario)
ALTER TABLE INVENTARIO ADD CONSTRAINT FK_INVENTARIO_PRODUCTO FOREIGN KEY (idProducto) REFERENCES PRODUCTO(idProducto)
ALTER TABLE INVENTARIO ADD CONSTRAINT UQ_INVENTARIO_PRODUCTO UNIQUE (idProducto)

-- Tablla Movimiento del inventario
CREATE TABLE MOVIMIENTO_INVENTARIO (
    idMovimiento INT NOT NULL,
    idInventario INT NOT NULL,
    tipoMovimiento NVARCHAR(30),
    cantidad INT,
    fechaMovimiento DATETIME,
    motivo NVARCHAR(255)
)
ALTER TABLE MOVIMIENTO_INVENTARIO ADD CONSTRAINT PK_MOVIMIENTO_INVENTARIO PRIMARY KEY (idMovimiento)
ALTER TABLE MOVIMIENTO_INVENTARIO ADD CONSTRAINT FK_MOVIMIENTO_INVENTARIO_INVENTARIO FOREIGN KEY (idInventario) REFERENCES INVENTARIO(idInventario)

-- Tabla Tipo de estados
CREATE TABLE TIPO_ESTADO (
    idTipoEstado INT NOT NULL,
    estado NVARCHAR(30)
)
ALTER TABLE TIPO_ESTADO ADD CONSTRAINT PK_TIPO_ESTADO PRIMARY KEY (idTipoEstado)

-- Tabla Estados
CREATE TABLE ESTADO (
    idEstado INT NOT NULL,
    idTipoEstado INT NOT NULL,
    nombreEstado NVARCHAR(50)
)
ALTER TABLE ESTADO ADD CONSTRAINT PK_ESTADO PRIMARY KEY (idEstado)
ALTER TABLE ESTADO ADD CONSTRAINT FK_ESTADO_TIPO_ESTADO FOREIGN KEY (idTipoEstado) REFERENCES TIPO_ESTADO(idTipoEstado)

-- Tabla Carrito
CREATE TABLE CARRITO (
    idCarrito INT NOT NULL,
    idCliente INT NOT NULL,
    idEstado INT NOT NULL,
    fechaCreacion DATETIME
)
ALTER TABLE CARRITO ADD CONSTRAINT PK_CARRITO PRIMARY KEY (idCarrito)
ALTER TABLE CARRITO ADD CONSTRAINT FK_CARRITO_CLIENTE FOREIGN KEY (idCliente) REFERENCES CLIENTE(idCliente)
ALTER TABLE CARRITO ADD CONSTRAINT FK_CARRITO_ESTADO FOREIGN KEY (idEstado) REFERENCES ESTADO(idEstado)

-- Tabla Detalle Carrito
CREATE TABLE DETALLE_CARRITO (
    idDetalleCarrito INT NOT NULL,
    idCarrito INT NOT NULL,
    idProducto INT NOT NULL,
    cantidad INT
)
ALTER TABLE DETALLE_CARRITO ADD CONSTRAINT PK_DETALLE_CARRITO PRIMARY KEY (idDetalleCarrito)
ALTER TABLE DETALLE_CARRITO ADD CONSTRAINT FK_DETALLE_CARRITO_CARRITO FOREIGN KEY (idCarrito) REFERENCES CARRITO(idCarrito)
ALTER TABLE DETALLE_CARRITO ADD CONSTRAINT FK_DETALLE_CARRITO_PRODUCTO FOREIGN KEY (idProducto) REFERENCES PRODUCTO(idProducto)

-- Tabla Pedido
CREATE TABLE PEDIDO (
    idPedido INT NOT NULL,
    idCliente INT NOT NULL,
    idDireccion INT NOT NULL,
    idEstado INT NOT NULL,
    fechaPedido DATETIME,
    totalPedido DECIMAL(12,2)
)
ALTER TABLE PEDIDO ADD CONSTRAINT PK_PEDIDO PRIMARY KEY (idPedido)
ALTER TABLE PEDIDO ADD CONSTRAINT FK_PEDIDO_CLIENTE FOREIGN KEY (idCliente) REFERENCES CLIENTE(idCliente)
ALTER TABLE PEDIDO ADD CONSTRAINT FK_PEDIDO_DIRECCION FOREIGN KEY (idDireccion) REFERENCES DIRECCION(idDireccion)
ALTER TABLE PEDIDO ADD CONSTRAINT FK_PEDIDO_ESTADO FOREIGN KEY (idEstado) REFERENCES ESTADO(idEstado)

-- Tabla Detalle Pedido
CREATE TABLE DETALLE_PEDIDO (
    idDetallePedido INT NOT NULL,
    idPedido INT NOT NULL,
    idProducto INT NOT NULL,
    cantidad INT,
    precioUnitario DECIMAL(12,2),
    subtotal DECIMAL(12,2)
)
ALTER TABLE DETALLE_PEDIDO ADD CONSTRAINT PK_DETALLE_PEDIDO PRIMARY KEY (idDetallePedido)
ALTER TABLE DETALLE_PEDIDO ADD CONSTRAINT FK_DETALLE_PEDIDO_PEDIDO FOREIGN KEY (idPedido) REFERENCES PEDIDO(idPedido)
ALTER TABLE DETALLE_PEDIDO ADD CONSTRAINT FK_DETALLE_PEDIDO_PRODUCTO FOREIGN KEY (idProducto) REFERENCES PRODUCTO(idProducto)

-- Tabla Metodo de pago
CREATE TABLE METODO_PAGO (
    idMetodoPago INT NOT NULL,
    nombreMetodo NVARCHAR(80),
    descripcionMetodo NVARCHAR(150),
    activo BIT
)
ALTER TABLE METODO_PAGO ADD CONSTRAINT PK_METODO_PAGO PRIMARY KEY (idMetodoPago)

-- Tabla Pago
CREATE TABLE PAGO (
    idPago INT NOT NULL,
    idPedido INT NOT NULL,
    idMetodoPago INT NOT NULL,
    idEstado INT NOT NULL,
    montoPago DECIMAL(12,2),
    fechaPago DATETIME,
    referenciaSimulada NVARCHAR(100)
)
ALTER TABLE PAGO ADD CONSTRAINT PK_PAGO PRIMARY KEY (idPago)
ALTER TABLE PAGO ADD CONSTRAINT FK_PAGO_PEDIDO FOREIGN KEY (idPedido) REFERENCES PEDIDO(idPedido)
ALTER TABLE PAGO ADD CONSTRAINT FK_PAGO_METODO_PAGO FOREIGN KEY (idMetodoPago) REFERENCES METODO_PAGO(idMetodoPago)
ALTER TABLE PAGO ADD CONSTRAINT FK_PAGO_ESTADO FOREIGN KEY (idEstado) REFERENCES ESTADO(idEstado)

-- Tabla historial envio
CREATE TABLE HISTORIAL_ESTADO_PEDIDO (
    idHistorial INT NOT NULL,
    idPedido INT NOT NULL,
    idEstado INT NOT NULL,
    fechaCambio DATETIME,
    observacion NVARCHAR(255)
)
ALTER TABLE HISTORIAL_ESTADO_PEDIDO ADD CONSTRAINT PK_HISTORIAL_ESTADO_PEDIDO PRIMARY KEY (idHistorial)
ALTER TABLE HISTORIAL_ESTADO_PEDIDO ADD CONSTRAINT FK_HISTORIAL_ESTADO_PEDIDO_PEDIDO FOREIGN KEY (idPedido) REFERENCES PEDIDO(idPedido)
ALTER TABLE HISTORIAL_ESTADO_PEDIDO ADD CONSTRAINT FK_HISTORIAL_ESTADO_PEDIDO_ESTADO FOREIGN KEY (idEstado) REFERENCES ESTADO(idEstado)

-- Tabla envio
CREATE TABLE ENVIO (
    idEnvio INT NOT NULL,
    idPedido INT NOT NULL,
    empresaTransporte NVARCHAR(100),
    codigoSeguimiento NVARCHAR(100),
    fechaEnvio DATETIME,
    fechaEntrega DATETIME,
    estadoEnvio NVARCHAR(30)
)
ALTER TABLE ENVIO ADD CONSTRAINT PK_ENVIO PRIMARY KEY (idEnvio)
ALTER TABLE ENVIO ADD CONSTRAINT FK_ENVIO_PEDIDO FOREIGN KEY (idPedido) REFERENCES PEDIDO(idPedido)
ALTER TABLE ENVIO ADD CONSTRAINT UQ_ENVIO_PEDIDO UNIQUE (idPedido)

-- Tabla Promocion
CREATE TABLE PROMOCION (
    idPromocion INT NOT NULL,
    nombrePromocion NVARCHAR(100),
    descripcionPromocion NVARCHAR(255),
    porcentajeDescuento DECIMAL(5,2),
    fechaInicio DATETIME,
    fechaFin DATETIME,
    activa BIT
)
ALTER TABLE PROMOCION ADD CONSTRAINT PK_PROMOCION PRIMARY KEY (idPromocion)

-- Tabla que relaciona las promociones con los pedidos
CREATE TABLE PEDIDO_PROMOCION (
    idPedido INT NOT NULL,
    idPromocion INT NOT NULL
)
ALTER TABLE PEDIDO_PROMOCION ADD CONSTRAINT PK_PEDIDO_PROMOCION PRIMARY KEY (idPedido, idPromocion)
ALTER TABLE PEDIDO_PROMOCION ADD CONSTRAINT FK_PEDIDO_PROMOCION_PEDIDO FOREIGN KEY (idPedido) REFERENCES PEDIDO(idPedido)
ALTER TABLE PEDIDO_PROMOCION ADD CONSTRAINT FK_PEDIDO_PROMOCION_PROMOCION FOREIGN KEY (idPromocion) REFERENCES PROMOCION(idPromocion)

-- Tabla Reseñas
CREATE TABLE RESENA (
    idResena INT NOT NULL,
    idCliente INT NOT NULL,
    idProducto INT NOT NULL,
    calificacion INT,
    comentario NVARCHAR(500),
    fechaResena DATETIME
)
ALTER TABLE RESENA ADD CONSTRAINT PK_RESENA PRIMARY KEY (idResena)
ALTER TABLE RESENA ADD CONSTRAINT FK_RESENA_CLIENTE FOREIGN KEY (idCliente) REFERENCES CLIENTE(idCliente)
ALTER TABLE RESENA ADD CONSTRAINT FK_RESENA_PRODUCTO FOREIGN KEY (idProducto) REFERENCES PRODUCTO(idProducto)
